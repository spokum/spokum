export function rulesHtml() {
  return RULES.map(
    (block) => `<div class="rule-block">
      <div class="row" style="gap:8px;margin-bottom:8px">
        <span style="color:var(--accent)">${icon(block.icon, 18)}</span>
        <span class="strong small">${esc(block.title)}</span>
      </div>
      ${block.lead ? `<p class="small" style="margin:0 0 8px;line-height:1.5">${esc(block.lead)}</p>` : ''}
      <ul class="rule-list">${block.items.map((item) => `<li>${esc(item)}</li>`).join('')}</ul>
      ${block.note ? `<div class="rule-note">${icon('warn', 15)}<span>${esc(block.note)}</span></div>` : ''}
    </div>`
  ).join('');
}

export function openRules() {
  const body = el(`<div class="col" style="gap:14px">
    <p class="tiny muted" style="margin:0;line-height:1.5">Действуют с момента регистрации. Дополняются по мере роста сети — о важных изменениях объявим в ленте.</p>
    ${rulesHtml()}
    <p class="tiny muted" style="margin:0;text-align:center">СпокУм. Здесь настроение важнее охватов.</p>
  </div>`);
  return openSheet('Правила СпокУма', body);
}
