function itemText(item) {
  return typeof item === 'string' ? item : item.t;
}

function itemPun(item) {
  return typeof item === 'string' ? null : PUN[item.pun] || null;
}

export function ruleList() {
  const flat = [];
  RULES.forEach((block, index) => {
    block.items.forEach((item, i) => {
      const pun = itemPun(item);
      if (!pun) return;
      flat.push({
        no: `${index + 1}.${i + 1}`,
        block: block.title,
        text: itemText(item),
        label: pun.label,
        tone: pun.tone,
        kind: pun.kind,
        minutes: pun.minutes
      });
    });
  });
  return flat;
}

export function rulesHtml() {
  return RULES.map(
    (block, index) => `<div class="rule-block">
      <div class="row" style="gap:8px;margin-bottom:8px">
        <span class="rule-num">${index + 1}</span>
        <span style="color:var(--accent)">${icon(block.icon, 17)}</span>
        <span class="strong small">${esc(block.title)}</span>
      </div>
      ${block.lead ? `<p class="small" style="margin:0 0 10px;line-height:1.5">${esc(block.lead)}</p>` : ''}
      <div class="rule-list">${block.items
        .map((item, i) => {
          const pun = itemPun(item);
          return `<div class="rule-item"><span class="rule-no">${index + 1}.${i + 1}</span><span class="grow">${esc(
            itemText(item)
          )}</span>${pun ? `<span class="rule-pun ${pun.tone}">${esc(pun.label)}</span>` : ''}</div>`;
        })
        .join('')}</div>
      ${block.note ? `<div class="rule-note">${icon('warn', 15)}<span>${esc(block.note)}</span></div>` : ''}
    </div>`
  ).join('');
}

export function openRules() {
  const body = el(`<div class="col" style="gap:14px">
    <p class="tiny muted" style="margin:0;line-height:1.5">Действуют с момента регистрации. Каждый пункт пронумерован — на него можно сослаться в жалобе или при разборе наказания. Метка справа показывает обычную меру за первое нарушение.</p>
    ${rulesHtml()}
    <p class="tiny muted" style="margin:0;text-align:center">СпокУм. Здесь настроение важнее охватов.</p>
  </div>`);
  return openSheet('Правила СпокУма', body);
}
